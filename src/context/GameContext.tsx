// Helper function to generate unique IDs
const generateId = (prefix: string = '') => `${prefix}${Date.now()}-${Math.random().toString(36).substr(2, 9)}`

const clamp = (value: number, min: number, max: number) => Math.min(Math.max(value, min), max)

const createFullFloorTiles = (width: number, height: number, texture?: string) => {
  const tiles: Array<{ x: number; y: number; texture?: string }> = []

  for (let x = 0; x < width; x++) {
    for (let y = 0; y < height; y++) {
      tiles.push({ x, y, texture })
    }
  }

  return tiles
}

const adjustDoorwayForFloorTiles = (
  doorway: { x: number; y: number; type: 'north-east' | 'north-west' } | undefined,
  floorTiles: Array<{ x: number; y: number }> | undefined,
  width: number,
  height: number
) => {
  if (!doorway) return undefined

  const effectiveFloorTiles = floorTiles && floorTiles.length > 0
    ? floorTiles
    : createFullFloorTiles(width, height)

  if (doorway.type === 'north-east') {
    const columnTiles = effectiveFloorTiles.filter(tile => tile.x === doorway.x)
    if (columnTiles.length === 0) return undefined
    const minY = Math.min(...columnTiles.map(tile => tile.y))
    return { x: doorway.x, y: minY - 1, type: 'north-east' as const }
  }

  const rowTiles = effectiveFloorTiles.filter(tile => tile.y === doorway.y)
  if (rowTiles.length === 0) return undefined
  const minX = Math.min(...rowTiles.map(tile => tile.x))
  return { x: minX - 1, y: doorway.y, type: 'north-west' as const }
}

const ensureRoomFloorTiles = (room: Room): Room => {
  const floorTiles = room.floorTiles && room.floorTiles.length > 0
    ? room.floorTiles
    : createFullFloorTiles(room.width, room.height)

  const doorway = adjustDoorwayForFloorTiles(room.doorway, floorTiles, room.width, room.height)

  return {
    ...room,
    floorTiles,
    doorway,
    walls: buildRoomWalls(room.width, room.height, doorway, floorTiles)
  }
}

const normalizeDoorway = (
  width: number,
  height: number,
  doorway?: { x: number; y: number; type: 'north-east' | 'north-west' }
) => {
  if (!doorway) return undefined

  if (doorway.type === 'north-east') {
    const x = clamp(Math.round(doorway.x), 0, Math.max(width - 1, 0))
    return { x, y: -1, type: 'north-east' as const }
  }

  const y = clamp(Math.round(doorway.y), 0, Math.max(height - 1, 0))
  return { x: -1, y, type: 'north-west' as const }
}

const normalizeSpawnPoint = (width: number, height: number, spawnPoint?: { x: number; y: number }) => {
  if (!spawnPoint) return undefined

  const x = clamp(Math.round(spawnPoint.x), 0, Math.max(width - 1, 0))
  const y = clamp(Math.round(spawnPoint.y), 0, Math.max(height - 1, 0))

  return { x, y }
}

export function buildRoomWalls(
  width: number,
  height: number,
  doorway?: { x: number; y: number; type: 'north-east' | 'north-west' },
  floorTiles?: Array<{ x: number; y: number }>
) {
  const effectiveFloorTiles = floorTiles && floorTiles.length > 0
    ? floorTiles
    : createFullFloorTiles(width, height)

  const tileSet = new Set(effectiveFloorTiles.map(tile => `${tile.x},${tile.y}`))
  const walls: Array<{ x: number; y: number; edge: WallEdge }> = []

  effectiveFloorTiles.forEach(tile => {
    // A tile with no floor to its -y gets a panel on that edge, and so on. The
    // doorway is simply a segment we skip.
    const westKey = `${tile.x},${tile.y - 1}`
    if (!tileSet.has(westKey)) {
      if (!(doorway?.type === 'north-east' && doorway.x === tile.x && doorway.y === tile.y - 1)) {
        walls.push({ x: tile.x, y: tile.y, edge: 'west' })
      }
    }

    const northKey = `${tile.x - 1},${tile.y}`
    if (!tileSet.has(northKey)) {
      if (!(doorway?.type === 'north-west' && doorway.x === tile.x - 1 && doorway.y === tile.y)) {
        walls.push({ x: tile.x, y: tile.y, edge: 'north' })
      }
    }
  })

  return walls
}

const defaultSpawnFromDoorway = (
  width: number,
  height: number,
  doorway?: { x: number; y: number; type: 'north-east' | 'north-west' }
) => {
  if (!doorway) {
    return { x: Math.floor(width / 2), y: Math.floor(height / 2) }
  }

  if (doorway.type === 'north-east') {
    return { x: clamp(doorway.x, 0, Math.max(width - 1, 0)), y: 0 }
  }

  return { x: 0, y: clamp(doorway.y, 0, Math.max(height - 1, 0)) }
}

const sanitizeLayoutRow = (row: string) => row.replace(/\s+$/u, '')

const determineDoorwayFromLayout = (
  doorCandidate: { x: number; y: number; orientation: 'north-east' | 'north-west' } | undefined,
  width: number,
  height: number
) => {
  if (!doorCandidate) return undefined

  if (doorCandidate.orientation === 'north-east') {
    return normalizeDoorway(width, height, { x: doorCandidate.x, y: -1, type: 'north-east' })
  }

  return normalizeDoorway(width, height, { x: -1, y: doorCandidate.y, type: 'north-west' })
}

const layoutCharIsFloor = (char: string) => {
  const normalized = char.toLowerCase()
  return normalized === 'o' || normalized === 'd' || normalized === 's'
}

export const createRoomFromLayoutDefinition = (definition: RoomLayoutDefinition): Room => {
  const rows = definition.layout.map(sanitizeLayoutRow)
  const height = rows.length || 1
  const width = rows.reduce((max, row) => Math.max(max, row.length), 0) || 1

  const floorTiles: Array<{ x: number; y: number }> = []
  let doorCandidate: { x: number; y: number; orientation: 'north-east' | 'north-west' } | undefined
  let spawnCandidate: { x: number; y: number } | undefined

  rows.forEach((row, y) => {
    for (let x = 0; x < width; x++) {
      const char = row[x] ?? 'x'
      if (layoutCharIsFloor(char)) {
        floorTiles.push({ x, y })
      }

      if ((char === 'd' || char === 'D') && !doorCandidate) {
        const orientation: 'north-east' | 'north-west' = x === 0 ? 'north-west' : 'north-east'
        doorCandidate = { x, y, orientation }
      }

      if ((char === 's' || char === 'S') && !spawnCandidate) {
        spawnCandidate = { x, y }
      }
    }
  })

  const uniqueFloorTiles = Array.from(
    new Map(floorTiles.map(tile => [`${tile.x},${tile.y}`, tile])).values()
  )

  const doorway = determineDoorwayFromLayout(doorCandidate, width, height)
  const baseFloorTiles = uniqueFloorTiles.length > 0
    ? uniqueFloorTiles
    : createFullFloorTiles(width, height)
  const adjustedDoorway = adjustDoorwayForFloorTiles(doorway, baseFloorTiles, width, height)

  const spawnPoint = normalizeSpawnPoint(
    width,
    height,
    spawnCandidate ?? defaultSpawnFromDoorway(width, height, adjustedDoorway)
  )

  const baseRoom: Room = {
    id: definition.id ?? generateId('room-'),
    name: definition.name,
    width,
    height,
    floorTiles: baseFloorTiles,
    furniture: [],
    walls: [],
    doorway: adjustedDoorway,
    spawnPoint
  }

  return ensureRoomFloorTiles(baseRoom)
}

export const serializeRoomLayout = (room: Room): RoomLayoutDefinition => {
  const grid = Array.from({ length: room.height }, () => Array.from({ length: room.width }, () => 'x'))
  const floorTiles = room.floorTiles && room.floorTiles.length > 0
    ? room.floorTiles
    : createFullFloorTiles(room.width, room.height)

  floorTiles.forEach(tile => {
    if (tile.y >= 0 && tile.y < room.height && tile.x >= 0 && tile.x < room.width) {
      grid[tile.y][tile.x] = 'o'
    }
  })

  if (room.spawnPoint) {
    const { x, y } = room.spawnPoint
    if (y >= 0 && y < room.height && x >= 0 && x < room.width) {
      grid[y][x] = 's'
    }
  }

  if (room.doorway) {
    if (room.doorway.type === 'north-east') {
      const columnTiles = floorTiles.filter(tile => tile.x === room.doorway!.x)
      if (columnTiles.length > 0) {
        const minY = Math.min(...columnTiles.map(tile => tile.y))
        if (minY >= 0 && minY < room.height && room.doorway!.x >= 0 && room.doorway!.x < room.width) {
          grid[minY][room.doorway!.x] = 'd'
        }
      }
    } else {
      const rowTiles = floorTiles.filter(tile => tile.y === room.doorway!.y)
      if (rowTiles.length > 0) {
        const minX = Math.min(...rowTiles.map(tile => tile.x))
        if (room.doorway!.y >= 0 && room.doorway!.y < room.height && minX >= 0 && minX < room.width) {
          grid[room.doorway!.y][minX] = 'd'
        }
      }
    }
  }

  const layout = grid.map(row => row.join(''))

  return {
    id: room.id,
    name: room.name,
    layout
  }
}

// Helper function to create a new room
const createRoom = (name: string, width: number, height: number, floorTexture?: string): Room => {
  const doorway = normalizeDoorway(width, height, {
    x: Math.floor(width / 2),
    y: -1,
    type: 'north-east'
  })

  const spawnPoint = normalizeSpawnPoint(width, height, {
    x: doorway?.x ?? Math.floor(width / 2),
    y: 0
  })

  const adjustedDoorway = adjustDoorwayForFloorTiles(doorway, undefined, width, height)

  return {
    id: generateId('room-'),
    name,
    width,
    height,
    floorTiles: createFullFloorTiles(width, height, floorTexture),
    furniture: [],
    walls: buildRoomWalls(width, height, adjustedDoorway),
    doorway: adjustedDoorway,
    spawnPoint,
    floorTexture
  }
}

// Provider
export function GameProvider({ children }: { children: ReactNode }) {
  const [state, dispatch] = useReducer(gameReducer, initialState)

  /** The last document we stored, so revisions increment rather than reset. */
  const savedWorld = useRef<WorldDocument | null>(null)
  /** Saving stays off until the world is loaded, or boot would overwrite it. */
  const hydrated = useRef(false)

  // Dev-only inspection hook. Reading the live room and player state from the
  // console (or a browser test) beats inferring it from canvas pixels.
  useEffect(() => {
    if (import.meta.env.DEV) {
      const debugWindow = window as unknown as { __isogame?: GameState }
      debugWindow.__isogame = state
    }
  }, [state])

  // Initialize game with default room and players
  useEffect(() => {
    const layoutDefinitions = Array.isArray(roomLayoutDefinitions)
      ? (roomLayoutDefinitions as RoomLayoutDefinition[])
      : []

    const validLayoutDefinitions = layoutDefinitions.filter(
      (definition): definition is RoomLayoutDefinition =>
        !!definition &&
        typeof definition.name === 'string' &&
        Array.isArray(definition.layout)
    )

    const predefinedRooms = validLayoutDefinitions.map(createRoomFromLayoutDefinition)
    const fallbackRooms = predefinedRooms.length > 0
      ? predefinedRooms
      : [createRoom('Main Room', 20, 15)]

    // A saved world wins over the shipped layouts; the layouts are the seed for
    // a first visit, not the source of truth afterwards.
    let cancelled = false

    const bootstrap = async () => {
      const [saved, profile] = await Promise.all([
        getWorldStore().load(),
        getProfileStore().load()
      ])
      if (cancelled) return

      const restored = saved?.rooms?.length
        ? saved.rooms.map(fromPersistedRoom)
        : null

      if (restored) savedWorld.current = saved

      const roomsToLoad = restored ?? fallbackRooms
      roomsToLoad.forEach(room => {
        dispatch({ type: 'ADD_ROOM', payload: room })
      })

      const defaultRoom =
        roomsToLoad.find(room => room.id === saved?.currentRoomId) ?? roomsToLoad[0]
      if (!defaultRoom) return

      dispatch({ type: 'SET_CURRENT_ROOM', payload: defaultRoom })
      startPlayers(defaultRoom, profile?.appearance ?? DEFAULT_APPEARANCE)
      hydrated.current = true
    }

    void bootstrap()
    return () => {
      cancelled = true
    }
  }, [])

  /**
   * Persist the world whenever the authored parts of it change.
   *
   * Debounced because painting a floor fires a dispatch per tile, and a save
   * per tile would be pointless locally and abusive against a server.
   */
  useEffect(() => {
    if (!hydrated.current || state.rooms.length === 0) return

    const timer = window.setTimeout(() => {
      const document = toWorldDocument(
        state.rooms,
        state.currentRoom?.id ?? null,
        savedWorld.current
      )
      void getWorldStore()
        .save(document)
        .then(stored => {
          savedWorld.current = stored
        })
    }, 600)

    return () => window.clearTimeout(timer)
  }, [state.rooms, state.currentRoom])

  /**
   * Seed the guests at the room's spawn point.
   *
   * Only the first is ours; the rest are given deterministic looks derived from
   * their id, so a room reads as populated by different people without any of
   * it being authored or stored.
   */
  const startPlayers = (defaultRoom: Room, appearance: Appearance) => {
    const spawnX = defaultRoom.spawnPoint?.x || 5
    const spawnY = defaultRoom.spawnPoint?.y || 5
    const outfits = getOutfits().map(outfit => outfit.id)
    const hairStyles = getHairStyles().map(style => style.id)

    const guests = [
      { name: 'Player1', color: '#FF6B6B' },
      { name: 'Player2', color: '#4ECDC4' },
      { name: 'Player3', color: '#45B7D1' },
      { name: 'Player4', color: '#96CEB4' }
    ]

    guests.forEach((guest, id) => {
      // Staggered so no two guests share a screen column. The old +1,+1 per
      // guest is a straight line *down the screen* in isometric, which stacked
      // all four into one overlapping pile.
      const x = spawnX + id
      const y = spawnY + (id % 2) * 2

      dispatch({
        type: 'ADD_PLAYER',
        payload: {
          id,
          ...guest,
          x,
          y,
          targetX: x,
          targetY: y,
          size: 0.8,
          isMoving: false,
          moveSpeed: 0.1,
          moveTimer: 0,
          moveDelay: 400,
          path: [],
          pathIndex: 0,
          action: 'idle',
          actionTimer: 0,
          actionDuration: 0,
          intent: null,
          lastDirection: 'south',
          appearance: id === 0 ? appearance : appearanceForSeed(id, outfits, hairStyles)
        }
      })
    })
  }

  // Room management functions
    const roomManager = {
      /** Forget the saved world and reload from the shipped layouts. */
      resetWorld: async () => {
        hydrated.current = false
        savedWorld.current = null
        await getWorldStore().clear()
        window.location.reload()
      },
      createRoom: (name: string, width: number, height: number, floorTexture?: string) => {
        const newRoom = createRoom(name, width, height, floorTexture)
        dispatch({ type: 'ADD_ROOM', payload: newRoom })
        return newRoom
      },
      selectRoom: (room: Room) => {
        dispatch({ type: 'SET_CURRENT_ROOM', payload: room })
      },
      deleteRoom: (roomId: string) => {
        dispatch({ type: 'DELETE_ROOM', payload: roomId })
      },
      renameRoom: (roomId: string, newName: string) => {
        dispatch({ type: 'RENAME_ROOM', payload: { roomId, newName } })
      },
      updateLayout: (roomId: string, layout: RoomLayoutUpdate) => {
        dispatch({ type: 'UPDATE_ROOM_LAYOUT', payload: { roomId, ...layout } })
      },
      setFloorTexture: (roomId: string, texture: string) => {
        dispatch({ type: 'SET_FLOOR_TEXTURE', payload: { roomId, texture } })
      },
      setTileTexture: (roomId: string, x: number, y: number, texture: string) => {
        dispatch({ type: 'SET_TILE_TEXTURE', payload: { roomId, x, y, texture } })
      }
    }

  /**
   * Dress the local player.
   *
   * Saved immediately rather than debounced: unlike painting a floor, this is
   * one deliberate change per interaction, and losing the last one to a reload
   * is exactly the thing people notice.
   */
  const setAppearance = (appearance: Appearance) => {
    dispatch({
      type: 'SET_PLAYER_APPEARANCE',
      payload: { playerId: state.currentPlayerId, appearance }
    })
    void getProfileStore().save(toProfileDocument(appearance))
  }

  return (
    <GameContext.Provider value={{ state, dispatch, roomManager, setAppearance }}>
      {children}
    </GameContext.Provider>
  )
}

// Hook
// This hook intentionally lives alongside the provider for convenient imports.
// eslint-disable-next-line react-refresh/only-export-components
export function useGame() {
  const context = useContext(GameContext)
  if (!context) {
    throw new Error('useGame must be used within a GameProvider')
  }
  return context
}
