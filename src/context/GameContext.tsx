  currentTool: 'move' | 'furniture' | 'room'
  selectedFurniture: string | null
  isPlacing: boolean
  rooms: Room[]
  currentRoom: Room | null
  players: Player[]
  currentPlayerId: number
  chatMessages: ChatMessage[]
  showChat: boolean
  contextMenuVisible: boolean
