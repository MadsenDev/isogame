// Types
export interface Player {
  id: number
  x: number
  y: number
  targetX: number
  targetY: number
  color: string
  name: string
  size: number
  isMoving: boolean
  moveSpeed: number
  moveTimer: number
  moveDelay: number
  path: Array<{ x: number; y: number }>
  pathIndex: number
  action: PlayerAction
  actionTimer: number
  /**
   * How long the action lasts, from the furniture's own data.
   *
   * 0 means "until they walk away", which is what sitting and lying are. The
   * loop used to expire every action after a hardcoded three seconds, which is
   * neither what the catalogue says nor what a chair should do.
   */
  actionDuration: number
  /**
   * What the player meant to do when they set off, if they clicked an object.
   *
   * Arriving somewhere is not the same as intending to use what is there:
   * without this, walking past a desk on the way to a chair would stop and use
   * the desk. Cleared on arrival.
   */
  intent: PlayerIntent | null
  lastDirection: string
  /** Hair, outfit and colours. Every player has one; only ours is editable. */
  appearance: Appearance
}

/**
 * One per interaction type the Sprite Factory can emit, plus the two the
 * context menu offers. A type the game cannot draw is a spot nothing can reach.
 */
export type PlayerAction = 'idle' | 'sitting' | 'laying' | 'using' | 'dancing' | 'waving'

export interface PlayerIntent {
  /** Interaction type to perform on arrival. */
  type: string
  /** The piece it belongs to, so a moved or deleted one is simply forgotten. */
  furnitureId: string
}

export interface Furniture {
  id: string
  x: number
  y: number
  type: string
  /** Rendered orientation. Defaults to the definition's default direction. */
  direction?: FurnitureDirection
  definition: FurnitureDefinition
}

export type FurnitureDirection = 'north' | 'south' | 'east' | 'west'

/** Where a piece can be placed. Generated by the Sprite Factory. */
export type FurniturePlacement = 'floor' | 'wall' | 'ceiling'

/**
 * One rendered orientation of a piece of furniture.
 *
 * `anchorX`/`anchorY` locate the centre of the piece's origin tile within the
 * sprite, which is what lets a 78px-tall bookshelf and a flat rug both be drawn
 * from the same tile coordinate without per-item fudge factors.
 */
/** A contact shadow, anchored to the same tile as the sprite it belongs to. */
export interface SpriteShadow {
  url: string
  file: string
  width: number
  height: number
  anchorX: number
  anchorY: number
}

export interface FurnitureSprite {
  url: string
  file: string
  index: number
  width: number
  height: number
  anchorX: number
  anchorY: number
  footprint: { width: number; height: number }
  interactions: FurnitureInteraction[]
  shadow?: SpriteShadow
}

export interface FurnitureDefinition {
  id: string
  name: string
  sprite: string
  width: number
  height: number
  interactions: FurnitureInteraction[]
  collision: FurnitureCollision
  walkable: boolean
  stackable: boolean
  rotatable: boolean
  category: 'seating' | 'decoration' | 'functional' | 'flooring' | 'wall'
  placement?: FurniturePlacement
  /** Orientation whose footprint matches `width`/`height`. */
  defaultDirection?: FurnitureDirection
  /** Every rendered orientation, keyed by direction. */
  sprites?: Record<string, FurnitureSprite>
  /** Every colour in the sprite, for palette-aware UI. */
  palette?: string[]
}

export interface FurnitureInteraction {
  type: 'sit' | 'lay' | 'stand' | 'use' | 'dance' | 'sleep'
  positions: FurniturePosition[]
  animation?: string
  duration?: number
}

export interface FurniturePosition {
  x: number
  y: number
  direction: 'north' | 'south' | 'east' | 'west' | 'north-east' | 'north-west' | 'south-east' | 'south-west'
  /**
   * Pixel offset from the tile's screen position to where the player's sprite
   * belongs - the seat of a chair, the mattress of a bed. Generated by
   * projecting the interaction point through the same camera as the sprite.
   */
  offsetX?: number
  offsetY?: number
  /** Whether the player draws over the furniture sprite or under it. */
  layer?: 'front' | 'behind'
}

export interface FurnitureCollision {
  blocksMovement: boolean
  blocksVision: boolean
  height: number // Height in tiles (0 = floor level, 1 = 1 tile high, etc.)
  shape: 'rectangle' | 'circle' | 'custom'
  customShape?: Array<{ x: number; y: number }>
}

export interface Room {
  id: string
  name: string
  width: number
  height: number
  floorTiles: Array<{ x: number; y: number; texture?: string }>
  furniture: Furniture[]
  /**
   * Wall panels, each on the edge of a floor tile it belongs to.
   *
   * Previously walls were stored on the empty tile *outside* the floor and then
   * drawn back two tiles with a magic offset. Anchoring them to the tile they
   * enclose means the sprite's own anchor positions them, with no fudge.
   */
  walls: Array<{ x: number; y: number; edge: WallEdge }>
  /**
   * Wall segments replaced by a window.
   *
   * Kept separate from `walls` so rebuilding the walls after a layout change
   * does not discard them; a window with no wall left under it is simply not
   * drawn.
   */
  windows?: Array<{ x: number; y: number; edge: WallEdge }>
  doorway?: { x: number; y: number; type: 'north-east' | 'north-west' }
  spawnPoint?: { x: number; y: number }
  floorTexture?: string
}

export interface RoomLayoutDefinition {
  id?: string
  name: string
  layout: string[]
}

export type RoomLayoutUpdate = {
  width: number
  height: number
  doorway?: { x: number; y: number; type: 'north-east' | 'north-west' }
  spawnPoint?: { x: number; y: number }
}

export interface ChatMessage {
  text: string
  timestamp: number
}

